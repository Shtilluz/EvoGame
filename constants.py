_used_herb: set = set()
_used_pred: set = set()
_used_scav: set = set()


def new_species_name(kind: str) -> str:
    """Возвращает уникальное имя для нового вида.

    kind — 'herb' / 'pred' / 'scav'
    Имена берутся из соответствующего пула; повторы исключаются до исчерпания пула.
    """
    if kind == "scav":
        pool, used = _SCAV_NAMES, _used_scav
    elif kind == "herb":
        pool, used = _HERB_NAMES, _used_herb
    else:
        pool, used = _PRED_NAMES, _used_pred
    names = [n for n in pool if n not in used] or pool
    name  = random.choice(names)
    used.add(name)
    return name


